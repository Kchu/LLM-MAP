"""
Language-model programs (LMPs) for the two planning modes:
  - llm_pddl:   LLM+MAP. The LLM writes the PDDL problem (objects, initial and goal states) as
                unified-planning Python code; the multi-agent FMAP planner and the single-agent
                BFWS planner then compute a bimanual plan. Planner errors are fed back to the LLM.
  - llm_direct: LLM-direct baseline. The LLM writes the bimanual plan itself as JSON.

API keys and endpoints are read from environment variables, never stored in code:
  OPENAI_API_KEY  (+ optional OPENAI_BASE_URL for an OpenAI-compatible endpoint)
  DEEPSEEK_API_KEY (+ optional DEEPSEEK_BASE_URL) for deepseek-* models
"""
import os, re, sys, time, json
import subprocess
from openai import OpenAI

from LLM.code_blocks import *
from LLM.prompts import pddl_system_message, pddl_rule_description, direct_rule_message, direct_system_message, choose_skill_desc
from log_utils import log


def get_client(model_name):
    """OpenAI-compatible client for the given model; credentials come from environment variables."""
    if model_name.startswith("deepseek"):
        api_key = os.environ.get("DEEPSEEK_API_KEY")
        if not api_key:
            raise EnvironmentError("Set DEEPSEEK_API_KEY to use deepseek models.")
        return OpenAI(api_key=api_key, base_url=os.environ.get("DEEPSEEK_BASE_URL", "https://api.deepseek.com"),
                      timeout=200, max_retries=5)
    if not os.environ.get("OPENAI_API_KEY"):
        raise EnvironmentError("Set OPENAI_API_KEY (and optionally OPENAI_BASE_URL) to use OpenAI models.")
    return OpenAI(timeout=200, max_retries=5)  # reads OPENAI_API_KEY / OPENAI_BASE_URL


def get_llm_response(client, model_name, messages, temperature):
    response = client.chat.completions.create(
        model=model_name,
        messages=messages,
        temperature=temperature
    )
    return response.choices[0].message.content

def extract_code_string(response_content):
    match = re.search(r'```python(.*?)```', response_content, re.DOTALL)
    return match.group(1).strip() if match else None

def write_plan_file(plan_file_path, domain_definition, ma_problem_initialization, plan2action, code_string, action_definition, solver_definition):
    plan_content = f"""
## System code string:
{domain_definition}
## Problem code string:
{ma_problem_initialization}
## Define plan2action function:
{plan2action}
## The following is generated by the LLM.
{'#' * 60}
{code_string}
## Action code string:
{action_definition}
## Solver code string:
{solver_definition}
"""
    with open(plan_file_path, 'w') as file:
        file.write(plan_content)

def execute_plan(plan_file_path):
    result = subprocess.run([sys.executable, plan_file_path], capture_output=True, text=True, check=True)
    return result.stdout.strip()

def llm_pddl(model_name, task_name, task_description, plan_file_path, temperature=0.0, max_trials=4, use_bfws=True):
    """use_bfws=True: plan with FMAP and BFWS and keep the shorter plan; False: FMAP only (no BFWS binary needed)."""
    tag = "LLM+MAP"
    if use_bfws:
        check_bfws()
    client = get_client(model_name)
    llm_time_cost, pddl_time_cost = 0, 0
    code_string = None

    messages = [
        {"role": "system", "content": pddl_system_message},
        {"role": "user", "content": task_description},
        {"role": "user", "content": pddl_rule_description}
    ]

    action_definition = choose_actions(task_name)
    solver_definition = get_map_solver_definition(use_bfws)
    # printed by the generated script when the (last) planner finds no valid plan
    no_plan_marker = "No BFWS plan found" if use_bfws else "No FMAP plan found"
    planners = "FMAP (multi-agent) and BFWS (single-agent)" if use_bfws else "FMAP (multi-agent) only"
    retry_prompt = "The code you generated is incorrect. There is no valid plan generated! Please check your definitions and regenerate based on the error above."

    for trial in range(max_trials):
        # Generate code from LLM
        log(tag, f"Trial {trial + 1}/{max_trials}: {model_name} is generating the PDDL problem code...")
        llm_start = time.time()
        response_content = get_llm_response(client, model_name, messages, temperature)
        llm_time_cost += round(time.time() - llm_start, 2)

        code_string = extract_code_string(response_content)
        if not code_string:
            log(tag, "No ```python code block in the LLM response, retrying...")
            continue

        # Write the generated code to file
        write_plan_file(plan_file_path, domain_definition, ma_problem_initialization, plan2action, code_string, action_definition, solver_definition)

        # Execute the generated plan
        log(tag, f"Solving the generated PDDL problem with {planners}...")
        try:
            pddl_start = time.time()
            # sys.executable: run the generated script with the same Python env as the caller
            result = subprocess.run([sys.executable, plan_file_path], capture_output=True, text=True, check=True)
            output = result.stdout.strip()
            pddl_time_cost += round(time.time() - pddl_start, 2)

            if no_plan_marker in output:
                print(output)
                if trial == max_trials - 1:
                    log(tag, f"No valid plan after {max_trials} trials.")
                    return code_string, output, llm_time_cost, pddl_time_cost
                log(tag, "Planners found no valid plan; sending the planner output back to the LLM.")
                messages.extend([
                {"role": "assistant", "content": code_string},
                {"role": "user", "content": output},
                {"role": "user", "content": retry_prompt}
                ])
                continue
            else:
                print(output)
                log(tag, f"Plan found (LLM: {llm_time_cost:.2f}s, planning: {pddl_time_cost:.2f}s).")
                return code_string, output, llm_time_cost, pddl_time_cost

        except subprocess.CalledProcessError as e:
            error_message = e.stderr.strip()
            print(error_message)
            log(tag, "The generated code raised an error; sending the error back to the LLM.")
            messages.extend([
                {"role": "assistant", "content": code_string},
                {"role": "user", "content": error_message},
                {"role": "user", "content": retry_prompt}
            ])
            continue  # Retry with updated messages

        except Exception as e:
            log(tag, f"Unexpected error: {e}")
            return code_string, None, llm_time_cost, pddl_time_cost

    log(tag, f"No valid plan after {max_trials} trials.")
    output = "No plan found! (The LLM failed to generate a correct task configuration.)"
    return code_string, output, llm_time_cost, pddl_time_cost


def llm_direct(model_name, task_name, task_description, plan_path):
    tag = "LLM-direct"
    messages = [
                {"role": "user", "content": direct_system_message},
                {"role": "user", "content": task_description+choose_skill_desc(task_name)},
                {"role": "user", "content": direct_rule_message},
                ]
    client = get_client(model_name)
    if model_name.startswith(("o1", "o3", "o4")):   # reasoning models: no temperature
        sampling = dict(top_p=1.0, frequency_penalty=0.0, presence_penalty=0.0)
    elif model_name.startswith("gpt"):
        sampling = dict(temperature=0, top_p=1.0, frequency_penalty=0.0, presence_penalty=0.0)
    else:
        sampling = dict(temperature=0.6)
    log(tag, f"{model_name} is generating the bimanual plan directly...")
    start_time = time.time()
    response = client.chat.completions.create(model=model_name, messages=messages, **sampling)
    time_cost = time.time() - start_time
    print(response.choices[0].message.content)
    try:
        result = response.choices[0].message.content
        pattern = r'```json\s*\n(.*?)\n```'
        matches = re.findall(pattern, result, re.DOTALL)
        plan = []
        for plan_items in matches:
            parsed_json = json.loads(plan_items)
            plan.append(parsed_json)
        plan_data = {"Left": [], "Right": []}
        if len(plan)==1: plan = plan[0]
        for step in plan:
            if "Left" in step:
                plan_data["Left"].append(step["Left"])
            else:
                plan_data["Left"].append("wait")

            if "Right" in step:
                plan_data["Right"].append(step["Right"])
            else:
                plan_data["Right"].append("wait")
        json_output = json.dumps(plan_data, indent=4)
        with open(plan_path, "w+", encoding="utf-8") as f:
            f.write(json_output)
        log(tag, f"Plan with {len(plan_data['Left'])} steps generated in {time_cost:.2f}s.")
    except Exception as e:
        json_output = None
        log(tag, f"No valid plan in the LLM response: {e}")
    return json_output, time_cost
